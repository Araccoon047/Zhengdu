/** 按关键词过滤（全部去掉空格后 includes，中文不用加分词） */
export function filterHubItems(items, keyword) {
  const kw = String(keyword || '').toLowerCase().replace(/\s+/g, '')
  if (!kw) return items
  return items.filter((it) => {
    const hay = (it.n + it.d + it.k + (it.where || '')).toLowerCase().replace(/\s+/g, '')
    return hay.includes(kw)
  })
}
